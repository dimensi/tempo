import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest';
import { openDatabase } from '@/server/db/connection';
import { migrate } from 'drizzle-orm/better-sqlite3/migrator';
import { user } from '@/server/db/schema';
import type { NutritionDayUpstream } from '@/server/yazio/adapter';
vi.mock('server-only', () => ({}));
const { nutritionRepository } = await import('@/server/nutrition/repository');
const { syncNutritionPeriod, boundedMap, periodDates } =
  await import('@/server/jobs/nutrition-sync');

let database: ReturnType<typeof openDatabase>;
let repository: ReturnType<typeof nutritionRepository>;
const date = '2026-01-01';
const nutrients = {
  'energy.energy': 1,
  'nutrient.protein': 0.1,
  'nutrient.fat': 0.2,
  'nutrient.carb': 0.3,
};
function upstream(): NutritionDayUpstream {
  return {
    items: vi.fn(async () => ({
      products: [
        {
          id: 'entry',
          date: date + ' 12:00:00',
          daytime: 'lunch' as const,
          product_id: 'product',
          amount: 10,
          serving: null,
          serving_quantity: null,
        },
      ],
      recipe_portions: [],
      simple_products: [],
    })),
    summary: vi.fn(async () => ({ meals: { lunch: { nutrients } } })),
    images: vi.fn(async () => ({})),
    product: vi.fn(async () => ({
      name: 'Synthetic product',
      base_unit: 'g',
      nutrients,
    })),
    recipe: vi.fn(async () => null),
  };
}
beforeEach(() => {
  database = openDatabase('file::memory:');
  migrate(database.db, { migrationsFolder: './drizzle' });
  database.db
    .insert(user)
    .values({
      id: 'owner',
      role: 'OWNER',
      name: 'Synthetic',
      email: 'synthetic@example.test',
      createdAt: new Date(),
      updatedAt: new Date(),
    })
    .run();
  // Temporary disposable DDL: central migration is generated by the coordinator only.

  repository = nutritionRepository(database);
});
afterEach(() => database.sqlite.close());
const period = { from: date, to: date };
describe('whole-day synchronization', () => {
  it('refreshes expired product and recipe cache rather than keeping stale nutrients forever', async () => {
    const source = upstream();
    vi.mocked(source.items).mockResolvedValue({
      products: [
        {
          id: 'product-entry',
          date: date + ' 12:00:00',
          daytime: 'lunch',
          product_id: 'product',
          amount: 1,
          serving: null,
          serving_quantity: null,
        },
      ],
      recipe_portions: [
        {
          id: 'recipe-entry',
          date: date + ' 12:00:00',
          daytime: 'lunch',
          recipe_id: 'recipe',
          portion_count: 1,
        },
      ],
      simple_products: [],
    });
    vi.mocked(source.recipe).mockResolvedValue({
      name: 'Synthetic recipe',
      portion_count: 1,
      nutrients,
      servings: [],
    });
    await syncNutritionPeriod('owner', period, source, repository);
    database.sqlite
      .prepare('UPDATE nutrition_cache SET fetched_at = ?')
      .run('2000-01-01T00:00:00.000Z');
    const changed = { ...nutrients, 'energy.energy': 2 };
    vi.mocked(source.product).mockResolvedValue({
      name: 'Changed synthetic product',
      base_unit: 'g',
      nutrients: changed,
    });
    vi.mocked(source.recipe).mockResolvedValue({
      name: 'Changed synthetic recipe',
      portion_count: 1,
      nutrients: changed,
      servings: [],
    });
    await syncNutritionPeriod('owner', period, source, repository);
    expect(source.product).toHaveBeenCalledTimes(2);
    expect(source.recipe).toHaveBeenCalledTimes(2);
    expect(repository.day('owner', date)!.meals[1]!.totals.calories).toBe('4');
  });
  it.each(['metadata', 'download'] as const)(
    'day-refresh persists successful empty food and retains existing photos on %s failure',
    async (failure) => {
      const source = upstream();
      vi.mocked(source.images).mockResolvedValue({
        lunch: 'https://images.yazio-cdn.com/synthetic.jpg',
      });
      const images = {
        fetch: vi.fn(async () => ({
          bytes: Buffer.from([1]),
          mime: 'image/jpeg',
        })),
        store: vi.fn(async () => ({
          storageKey: 'a'.repeat(64),
          contentHash: 'a'.repeat(64),
        })),
      };
      await syncNutritionPeriod('owner', period, source, repository, images);
      const oldPhoto = repository.photo('owner', `owner:${date}:lunch:yazio`);
      expect(
        repository.day('owner', date)!.meals[1]!.entries.length,
      ).toBeGreaterThan(0);
      vi.mocked(source.items).mockResolvedValue({
        products: [],
        recipe_portions: [],
        simple_products: [],
      });
      if (failure === 'metadata')
        vi.mocked(source.images).mockRejectedValue(
          new Error('Synthetic unavailable photo metadata'),
        );
      else
        images.fetch.mockRejectedValue(
          new Error('Synthetic unavailable photo bytes'),
        );
      const result = await syncNutritionPeriod(
        'owner',
        period,
        source,
        repository,
        images,
        { photoFailurePolicy: 'independent' },
      );
      expect(result).toMatchObject({
        state: 'partial',
        completedDates: [date],
        skippedDates: [],
        failedDates: [],
        photoFailedDates: [date],
      });
      expect(
        repository
          .day('owner', date)!
          .meals.every((meal) => meal.entries.length === 0),
      ).toBe(true);
      expect(repository.photo('owner', `owner:${date}:lunch:yazio`)).toEqual(
        oldPhoto,
      );
    },
  );
  it('independent photo metadata failure preserves newly fetched food but food failure still preserves the old snapshot', async () => {
    const source = upstream();
    vi.mocked(source.images).mockRejectedValue(
      new Error('Synthetic photo metadata error'),
    );
    const result = await syncNutritionPeriod(
      'owner',
      period,
      source,
      repository,
      undefined,
      { photoFailurePolicy: 'independent' },
    );
    expect(result).toMatchObject({
      state: 'partial',
      completedDates: [date],
      skippedDates: [],
      failedDates: [],
      photoFailedDates: [date],
    });
    const old = repository.day('owner', date);
    expect(old!.meals[1]!.totals.calories).toBe('10');
    vi.mocked(source.summary).mockRejectedValue(
      new Error('Synthetic food error'),
    );
    expect(
      await syncNutritionPeriod(
        'owner',
        period,
        source,
        repository,
        undefined,
        { photoFailurePolicy: 'independent' },
      ),
    ).toMatchObject({
      state: 'failed',
      completedDates: [],
      skippedDates: [],
      failedDates: [date],
    });
    expect(repository.day('owner', date)).toEqual(old);
  });
  it('is idempotent, caches references, and preserves exact normalized totals/issues', async () => {
    const source = upstream();
    expect(
      (await syncNutritionPeriod('owner', period, source, repository)).state,
    ).toBe('completed');
    const first = repository.day('owner', date)!;
    await syncNutritionPeriod('owner', period, source, repository);
    const second = repository.day('owner', date)!;
    expect({ ...second, fetchedAt: first.fetchedAt }).toEqual(first);
    expect(source.product).toHaveBeenCalledTimes(1);
    expect(second.meals[1]!.totals.calories).toBe('10');
    expect(second.meals[1]!.delta.calories).toBe('9');
    expect(repository.list('owner', date, date)).toHaveLength(1);
  });
  it('keeps the old snapshot on items, summary, reference, or photo failure', async () => {
    await syncNutritionPeriod('owner', period, upstream(), repository);
    const old = repository.day('owner', date);
    for (const endpoint of ['items', 'summary', 'images'] as const) {
      const source = upstream();
      vi.mocked(source[endpoint]).mockRejectedValue(
        new Error('Synthetic upstream error'),
      );
      expect(
        (await syncNutritionPeriod('owner', period, source, repository)).state,
      ).toBe('failed');
      expect(repository.day('owner', date)).toEqual(old);
    }
    const source = upstream();
    vi.mocked(source.items).mockResolvedValue({
      products: [
        {
          id: 'new',
          date: date + ' 12:00:00',
          daytime: 'lunch',
          product_id: 'uncached',
          amount: 1,
          serving: null,
          serving_quantity: null,
        },
      ],
      recipe_portions: [],
      simple_products: [],
    });
    vi.mocked(source.product).mockRejectedValue(new Error('Unavailable'));
    await syncNutritionPeriod('owner', period, source, repository);
    expect(repository.day('owner', date)).toEqual(old);
    vi.mocked(source.items).mockResolvedValue({
      products: [],
      recipe_portions: [],
      simple_products: [],
    });
    vi.mocked(source.images).mockResolvedValue({
      lunch: 'https://images.yazio-cdn.com/synthetic.jpg',
    });
    await syncNutritionPeriod('owner', period, source, repository, {
      fetch: async () => {
        throw new Error('Unavailable');
      },
      store: vi.fn(),
    });
    expect(repository.day('owner', date)).toEqual(old);
  });
  it('deletes missing upstream entries/photos only after success and keeps manual photos', async () => {
    const source = upstream();
    vi.mocked(source.images).mockResolvedValue({
      lunch: 'https://images.yazio-cdn.com/synthetic.jpg',
    });
    const storage = {
      fetch: async () => ({
        bytes: Buffer.from([255, 216, 255, 0]),
        mime: 'image/jpeg',
      }),
      store: async () => ({
        storageKey: 'a'.repeat(64),
        contentHash: 'a'.repeat(64),
      }),
    };
    await syncNutritionPeriod('owner', period, source, repository, storage);
    repository.addPhoto({
      id: 'manual',
      ownerId: 'owner',
      date,
      daytime: 'lunch',
      source: 'manual',
      storageKey: 'b'.repeat(64),
      contentHash: 'b'.repeat(64),
      sourceUrl: null,
      observedAt: new Date().toISOString(),
      mime: 'image/jpeg',
    });
    expect(repository.photos('owner', date)).toHaveLength(2);
    expect(repository.photos('owner', date)[0]).not.toHaveProperty('sourceUrl');
    vi.mocked(source.images).mockResolvedValue({});
    vi.mocked(source.items).mockResolvedValue({
      products: [],
      recipe_portions: [],
      simple_products: [],
    });
    await syncNutritionPeriod('owner', period, source, repository, storage);
    expect(
      repository.day('owner', date)!.meals.flatMap((m) => m.entries),
    ).toHaveLength(0);
    expect(repository.photos('owner', date).map((p) => p.id)).toEqual([
      'manual',
    ]);
    expect(repository.deleteManual('another-owner', 'manual')).toBe(false);
    expect(repository.deleteManual('owner', 'manual')).toBe(true);
  });
  it('makes validated food available when a photo download fails without claiming completion', async () => {
    const source = upstream();
    vi.mocked(source.images).mockResolvedValue({
      lunch: 'https://images.yazio-cdn.com/synthetic.jpg',
    });
    const result = await syncNutritionPeriod(
      'owner',
      period,
      source,
      repository,
      {
        fetch: async () => {
          throw new Error('Photo transport unavailable');
        },
        store: vi.fn(),
      },
    );
    expect(result).toMatchObject({
      state: 'partial',
      completedDates: [date],
      skippedDates: [],
      failedDates: [],
      photoFailedDates: [date],
    });
    expect(
      repository.day('owner', date)!.meals.flatMap((meal) => meal.entries),
    ).toHaveLength(1);
    expect(repository.photos('owner', date)).toEqual([]);
  });
  it('retains the existing failed photo slot and manual photos while refreshing valid food', async () => {
    const source = upstream();
    vi.mocked(source.images).mockResolvedValue({
      lunch: 'https://images.yazio-cdn.com/old.jpg',
    });
    await syncNutritionPeriod('owner', period, source, repository, {
      fetch: async () => ({
        bytes: Buffer.from([255, 216, 255, 0]),
        mime: 'image/jpeg',
      }),
      store: async () => ({
        storageKey: 'a'.repeat(64),
        contentHash: 'a'.repeat(64),
      }),
    });
    const photo = repository.photo('owner', `owner:${date}:lunch:yazio`);
    repository.addPhoto({
      id: 'manual',
      ownerId: 'owner',
      date,
      daytime: 'lunch',
      source: 'manual',
      storageKey: 'b'.repeat(64),
      contentHash: 'b'.repeat(64),
      sourceUrl: null,
      observedAt: new Date().toISOString(),
      mime: 'image/jpeg',
    });
    const items = await source.items(date);
    vi.mocked(source.items).mockResolvedValue({
      ...items,
      products: items.products.map((entry) => ({ ...entry, amount: 20 })),
    });
    vi.mocked(source.images).mockResolvedValue({
      lunch: 'https://images.yazio-cdn.com/new.jpg',
    });
    const result = await syncNutritionPeriod(
      'owner',
      period,
      source,
      repository,
      {
        fetch: async () => {
          throw new Error('Photo timeout');
        },
        store: vi.fn(),
      },
    );
    expect(result).toMatchObject({
      state: 'partial',
      completedDates: [date],
      skippedDates: [],
      failedDates: [],
      photoFailedDates: [date],
    });
    expect(repository.day('owner', date)!.meals[1]!.totals.calories).toBe('20');
    expect(repository.photo('owner', `owner:${date}:lunch:yazio`)).toEqual(
      photo,
    );
    expect(repository.photo('owner', 'manual')).not.toBeNull();
  });
  it('rejects overlapping sync and resumes after completion', async () => {
    const source = upstream();
    let release!: () => void;
    vi.mocked(source.items).mockImplementation(async () => {
      await new Promise<void>((r) => {
        release = r;
      });
      return { products: [], recipe_portions: [], simple_products: [] };
    });
    const run = syncNutritionPeriod('owner', period, source, repository);
    await expect(
      syncNutritionPeriod('owner', period, upstream(), repository),
    ).rejects.toThrow('Sync already running');
    release();
    await run;
    expect(
      (await syncNutritionPeriod('owner', period, upstream(), repository))
        .state,
    ).toBe('completed');
  });
});
it('bounds concurrency, waits for all workers on failure, and validates inclusive dates', async () => {
  let active = 0;
  let peak = 0;
  await expect(
    boundedMap([0, 1, 2, 3, 4], 2, async (value) => {
      active++;
      peak = Math.max(peak, active);
      await new Promise((r) => setTimeout(r, 1));
      active--;
      if (value === 0) throw new Error('Synthetic');
      return value;
    }),
  ).rejects.toThrow('Synthetic');
  expect(peak).toBe(2);
  expect(active).toBe(0);
  expect(periodDates({ from: '2024-02-28', to: '2024-03-01' })).toEqual([
    '2024-02-28',
    '2024-02-29',
    '2024-03-01',
  ]);
  expect(() => periodDates({ from: '2026-02-01', to: '2026-01-01' })).toThrow();
});

it('food-only synchronization never reads or persists health capabilities', async () => {
  const source = { ...upstream(), healthSummary: vi.fn(), weight: vi.fn() };
  await syncNutritionPeriod('owner', period, source, repository);
  expect(source.healthSummary).not.toHaveBeenCalled();
  expect(source.weight).not.toHaveBeenCalled();
  expect(
    database.sqlite.prepare('SELECT * FROM yazio_daily_steps').all(),
  ).toEqual([]);
  expect(
    database.sqlite.prepare('SELECT * FROM yazio_weight_entries').all(),
  ).toEqual([]);
});
