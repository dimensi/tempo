const dayWord = (count: number) =>
  count % 100 >= 11 && count % 100 <= 14
    ? 'дней'
    : count % 10 === 1
      ? 'день'
      : count % 10 >= 2 && count % 10 <= 4
        ? 'дня'
        : 'дней';
